import type { NPC, PC } from './types';

type PcDef = Omit<PC, 'hp' | 'status' | 'effects' | 'mask' | 'dmNote'> & Partial<Pick<PC, 'mask'>>;
const pc = (d: PcDef): PC => ({ hp: d.hpMax, status: 'alive', effects: [], mask: d.mask ?? '', dmNote: '', ...d });

type NpcDef = Omit<NPC, 'status' | 'hp' | 'phase' | 'dmNote'> & Partial<Pick<NPC, 'status'>>;
const npc = (d: NpcDef): NPC => ({
  status: d.status ?? 'unmet',
  hp: d.stat?.hp ?? null,
  phase: 0,
  dmNote: '',
  dialogue: DIALOGUE[d.id],
  ...d,
});

