import type { Ability, Clue, Condition, Item } from './types';

type ItemDef = Omit<Item, 'state' | 'holder' | 'qty' | 'ammo' | 'revealed' | 'dmNote'> &
  Partial<Pick<Item, 'state' | 'holder' | 'qty' | 'ammo' | 'revealed'>>;
const item = (d: ItemDef): Item => ({
  state: 'unclaimed',
  holder: '',
  qty: null,
  ammo: d.ammoMax ?? null,
  revealed: !d.secret,
  dmNote: '',
  ...d,
});

type AbilityDef = Omit<Ability, 'used' | 'enabled' | 'revealed' | 'dmNote'> & Partial<Pick<Ability, 'enabled'>>;
const ability = (d: AbilityDef): Ability => ({ used: 0, enabled: true, revealed: !d.secret, dmNote: '', ...d });

